/**
 * Pure TypeScript PDF-1.4 Binary Generator for React Native / Expo.
 * Produces valid, compliant PDF files with accurate cross-reference tables (xref),
 * page trees, Helvetica fonts, margins, text wrapping, and trailers.
 * Supported by all standard PDF readers (Adobe, Chrome, Google Drive, Android PDF Viewer).
 */

export interface PdfDocumentOptions {
  title?: string;
  author?: string;
  subject?: string;
  fontSize?: number;
  lineHeight?: number;
}

export class SimplePdfGenerator {
  /**
   * Escape text for PDF string literals `(text)`
   */
  private static escapePdfString(text: string): string {
    return text
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)')
      .replace(/[^\x20-\x7E\r\n\t]/g, ' '); // Map non-ASCII Latin1 to safe ASCII
  }

  /**
   * Wrap text into lines of max characters
   */
  private static wrapText(text: string, maxCharsPerLine = 78): string[] {
    const rawParagraphs = text.split(/\r?\n/);
    const lines: string[] = [];

    for (const paragraph of rawParagraphs) {
      if (paragraph.trim().length === 0) {
        lines.push('');
        continue;
      }

      const words = paragraph.split(/\s+/);
      let currentLine = '';

      for (const word of words) {
        if (!currentLine) {
          currentLine = word;
        } else if ((currentLine + ' ' + word).length <= maxCharsPerLine) {
          currentLine += ' ' + word;
        } else {
          lines.push(currentLine);
          currentLine = word;
        }
      }
      if (currentLine) {
        lines.push(currentLine);
      }
    }

    return lines;
  }

  /**
   * Generate valid PDF 1.4 binary string
   */
  static generate(text: string, options: PdfDocumentOptions = {}): string {
    const title = options.title || 'eyoTools Generated Document';
    const author = options.author || 'eyoTools Mobile Engine';
    const linesPerPage = 46;
    const allLines = this.wrapText(text);

    // Split lines into pages
    const pages: string[][] = [];
    if (allLines.length === 0) {
      pages.push(['(Empty document)']);
    } else {
      for (let i = 0; i < allLines.length; i += linesPerPage) {
        pages.push(allLines.slice(i, i + linesPerPage));
      }
    }

    const totalPages = pages.length;

    // Objects list:
    // 1 0 obj: Catalog
    // 2 0 obj: Pages
    // 3 0 obj: Font Helvetica
    // 4 0 obj: Font Helvetica-Bold
    // For each page i (0 to totalPages-1):
    //   Page object: obj (5 + i*2)
    //   Content stream: obj (6 + i*2)
    const objects: { id: number; content: string }[] = [];

    // Font regular
    objects.push({
      id: 3,
      content: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    });

    // Font bold
    objects.push({
      id: 4,
      content: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
    });

    const pageObjIds: number[] = [];

    pages.forEach((pageLines, pageIndex) => {
      const pageObjId = 5 + pageIndex * 2;
      const contentObjId = 6 + pageIndex * 2;
      pageObjIds.push(pageObjId);

      // Construct content stream
      let stream = 'BT\n';
      // Header
      stream += '/F2 13 Tf\n'; // Helvetica-Bold
      stream += '50 790 Td\n';
      stream += `(${this.escapePdfString(title.slice(0, 50))}) Tj\n`;

      // Header line
      stream += '/F1 8 Tf\n';
      stream += '0 -14 Td\n';
      stream += `(Generated by ${this.escapePdfString(author)} • Page ${pageIndex + 1} of ${totalPages}) Tj\n`;

      // Body text
      stream += '/F1 10 Tf\n';
      stream += '0 -22 Td\n';

      for (let j = 0; j < pageLines.length; j++) {
        const line = pageLines[j];
        if (j > 0) {
          stream += '0 -15 Td\n';
        }
        if (line) {
          stream += `(${this.escapePdfString(line)}) Tj\n`;
        }
      }

      stream += 'ET\n';

      const streamBytesLen = stream.length;

      // Page Object
      objects.push({
        id: pageObjId,
        content: `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Contents ${contentObjId} 0 R /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> >>`,
      });

      // Content Stream Object
      objects.push({
        id: contentObjId,
        content: `<< /Length ${streamBytesLen} >>\nstream\n${stream}endstream`,
      });
    });

    // Catalog & Pages
    const kidsStr = pageObjIds.map((id) => `${id} 0 R`).join(' ');
    objects.unshift({
      id: 2,
      content: `<< /Type /Pages /Kids [${kidsStr}] /Count ${totalPages} >>`,
    });
    objects.unshift({
      id: 1,
      content: `<< /Type /Catalog /Pages 2 0 R >>`,
    });

    // Sort objects by id
    objects.sort((a, b) => a.id - b.id);

    // Build PDF body with byte offset tracking for xref
    let pdf = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
    const offsets: number[] = [];

    // offset 0 is dummy for xref
    offsets.push(0);

    for (const obj of objects) {
      offsets[obj.id] = pdf.length;
      pdf += `${obj.id} 0 obj\n${obj.content}\nendobj\n`;
    }

    const startXref = pdf.length;
    const totalObjs = objects.length + 1;

    pdf += `xref\n0 ${totalObjs}\n`;
    pdf += '0000000000 65535 f \n';

    for (let i = 1; i < totalObjs; i++) {
      const offset = offsets[i] || 0;
      const offsetPadded = String(offset).padStart(10, '0');
      pdf += `${offsetPadded} 00000 n \n`;
    }

    pdf += `trailer\n<< /Size ${totalObjs} /Root 1 0 R >>\nstartxref\n${startXref}\n%%EOF\n`;

    return pdf;
  }
}
